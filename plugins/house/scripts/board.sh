#!/bin/sh
# Stop + UserPromptSubmit. Keeps the personal GitHub board current: when a session
# stops to wait on the user, the card it is working on is flagged `needs-me`; when
# the user replies in that session, the flag comes off and the card is `doing`.
#
#   bash board.sh stop     # Stop: the last message has a `user-only:` line -> flag
#   bash board.sh prompt   # UserPromptSubmit: this session flagged a card -> clear
#
# The board is plain GitHub issues and labels across every repo the trusted owners
# hold, read with one search (see commands/board.md). Labels, not a GitHub Project:
# cloud sessions get GitHub's REST API but not GraphQL, and Projects are
# GraphQL-only -- so are most `gh issue`/`gh pr` subcommands, which is why every
# call here is `gh api` against a REST path.
#
# Which card is "this session's", in order:
#   1. the one this hook already flagged for this session (a marker file);
#   2. `git config branch.<branch>.house-issue <n>`, set when work starts on one;
#   3. an issue the branch's open PR closes ("Closes #12" in its body);
#   4. that open PR itself;
#   5. none of the above: a new issue titled from the `user-only:` reason, so a
#      blocker never sits only in a transcript nobody is reading.
#
# Acts only where origin is github.com/<trusted owner>/<repo>. A work repo with
# no GitHub remote, or someone else's repo, gets nothing -- not a call, not a
# file. Trusted owners: HOUSE_TRUSTED_OWNERS, as in owner-allow.sh.
#
# Never blocks, never prompts: every path exits 0. FAIL OPEN like every house
# hook -- no python, no gh, no network, an unexpected answer: silence.
#
# shellcheck disable=SC2016
# The single-quoted block passed to `house_py -c` is python source.

SCRIPT_DIR=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
. "$SCRIPT_DIR/lib.sh"

mode="${1:-}"
case "$mode" in stop|prompt) ;; *) exit 0 ;; esac

command -v gh >/dev/null 2>&1 || exit 0

input=$(cat)

printf '%s' "$input" | house_py -c '
import hashlib, json, os, re, subprocess, sys, urllib.parse

mode = sys.argv[1]
try:
    payload = json.loads(sys.stdin.read() or "{}")
except Exception:
    sys.exit(0)
if not isinstance(payload, dict):
    sys.exit(0)

NEEDS, DOING = "needs-me", "doing"
LABELS = {
    NEEDS: ("d93f0b", "A Claude session is waiting on you"),
    DOING: ("0e8a16", "A Claude session is working on this"),
}
OWNERS = {o.lower() for o in re.split(r"[,\s]+",
          os.environ.get("HOUSE_TRUSTED_OWNERS") or "cameron-adrian") if o.strip()}
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"

sid = str(payload.get("session_id") or "")
if not sid:
    sys.exit(0)        # nothing to key the session-to-card link on
state_dir = os.environ.get("CLAUDE_PLUGIN_DATA") or os.environ.get("TMPDIR") or "/tmp"
marker = os.path.join(state_dir, "house-board-" + re.sub(r"[^\w.-]", "_", sid))


def run(args, cwd=None, stdin=None):
    try:
        r = subprocess.run(args, cwd=cwd, input=stdin, capture_output=True,
                           text=True, timeout=10)
        return r.returncode, r.stdout
    except Exception:
        return 1, ""


def api(method, path, body=None):
    """One REST call. Parsed JSON on success ({} for an empty body), None on failure."""
    args = ["gh", "api", "-X", method, path]
    if body is not None:
        args += ["--input", "-"]
    rc, out = run(args, stdin=json.dumps(body) if body is not None else None)
    if rc != 0:
        return None
    try:
        return json.loads(out) if out.strip() else {}
    except Exception:
        return {}


def load():
    try:
        with open(marker, encoding="utf-8") as fh:
            d = json.load(fh)
        return d if isinstance(d, dict) else None
    except Exception:
        return None


def save(d):
    try:
        os.makedirs(state_dir, exist_ok=True)
        with open(marker, "w", encoding="utf-8") as fh:
            json.dump(d, fh)
    except Exception:
        pass


def owned_repo(cwd):
    rc, url = run(["git", "remote", "get-url", "origin"], cwd=cwd)
    if rc != 0:
        return None
    u = re.sub(r"\.git/?$", "", url.strip())
    m = (re.match(r"^[^/@]+@([^:/]+):(.+)$", u)
         or re.match(r"^[a-zA-Z][\w+.-]*://(?:[^@/]+@)?([^/]+)/(.+)$", u))
    if not m:
        return None
    host = m.group(1).lower()
    if host != "github.com" and not host.endswith(".github.com"):
        return None
    parts = [p for p in m.group(2).split("/") if p]
    if len(parts) != 2 or parts[0].lower() not in OWNERS:
        return None
    return parts[0] + "/" + parts[1]


def session_link():
    rid = os.environ.get("CLAUDE_CODE_REMOTE_SESSION_ID", "")
    if rid.startswith("cse_"):
        return "https://claude.ai/code/session_" + rid[4:]
    return ""


# ---------------------------------------------------------------- prompt ----
if mode == "prompt":
    st = load()
    if not st or not st.get("flagged"):
        sys.exit(0)
    repo, num = st.get("repo"), st.get("number")
    api("DELETE", f"repos/{repo}/issues/{num}/labels/{NEEDS}")
    if not st.get("is_pr"):
        api("POST", f"repos/{repo}/issues/{num}/labels", {"labels": [DOING]})
    st["flagged"] = False
    save(st)
    ref = f"{repo}#{num}"
    print(f"Board: the card for this session is {ref}. You replied, so its `{NEEDS}` "
          f"label is off" + ("" if st.get("is_pr") else f" and it is `{DOING}` again")
          + "." + ("" if st.get("is_pr") else
                   f" Put `Closes #{num}` in the body of the PR for this work, "
                   "so merging it closes the card."))
    sys.exit(0)

# ------------------------------------------------------------------ stop ----
text = str(payload.get("last_assistant_message") or "")
path = str(payload.get("transcript_path") or "")
if not text.strip() and path and os.path.isfile(path):
    # Older versions do not send the message; take the last assistant text
    # from the transcript, skipping subagents (same reading as handoff-guard).
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            for line in fh:
                try:
                    d = json.loads(line)
                except Exception:
                    continue
                if not isinstance(d, dict) or d.get("type") != "assistant" or d.get("isSidechain"):
                    continue
                c = (d.get("message") or {}).get("content")
                parts = [c] if isinstance(c, str) else [
                    b.get("text", "") for b in (c if isinstance(c, list) else [])
                    if isinstance(b, dict) and b.get("type") == "text"]
                joined = "\n".join(x for x in parts if x)
                if joined.strip():
                    text = joined
    except Exception:
        sys.exit(0)

m = re.search(r"user-only:\s*(\S[^\n]*)", text, re.I)
if not m:
    sys.exit(0)
reason = re.sub(r"[*_`]+", "", m.group(1)).strip()[:300]
if not reason:
    sys.exit(0)

cwd = str(payload.get("cwd") or "") or os.getcwd()
if not os.path.isdir(cwd):
    sys.exit(0)
repo = owned_repo(cwd)
if not repo:
    sys.exit(0)        # local-only work repo, or not ours: the board never sees it

rc, branch = run(["git", "rev-parse", "--abbrev-ref", "HEAD"], cwd=cwd)
branch = branch.strip() if rc == 0 else ""
digest = hashlib.sha1(reason.encode("utf-8")).hexdigest()[:12]

st = load()
if st and st.get("repo") == repo and st.get("flagged") and st.get("digest") == digest:
    sys.exit(0)        # this exact blocker is already on the card

number, is_pr = None, False
if st and st.get("repo") == repo:
    number, is_pr = st.get("number"), bool(st.get("is_pr"))
if number is None and branch and branch != "HEAD":
    rc, cfg = run(["git", "config", "--get", f"branch.{branch}.house-issue"], cwd=cwd)
    hit = re.search(r"(\d+)", cfg) if rc == 0 else None
    if hit:
        number = int(hit.group(1))
if number is None and branch and branch != "HEAD":
    owner = repo.split("/")[0]
    head = urllib.parse.quote(f"{owner}:{branch}", safe="/:")
    pulls = api("GET", f"repos/{repo}/pulls?state=open&head={head}")
    if isinstance(pulls, list) and pulls:
        pr = pulls[0]
        hit = re.search(r"\b(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?)\s+#(\d+)",
                        str(pr.get("body") or ""), re.I)
        if hit:
            number = int(hit.group(1))
        elif pr.get("number"):
            number, is_pr = int(pr["number"]), True

# A card that is already closed would vanish from the board: start a fresh one.
if number is not None and not is_pr:
    cur = api("GET", f"repos/{repo}/issues/{number}")
    if not isinstance(cur, dict) or cur.get("state") != "open":
        number = None

for name, (color, desc) in LABELS.items():
    api("POST", f"repos/{repo}/labels",
        {"name": name, "color": color, "description": desc})   # 422 if it exists: fine

link = session_link()
where = [f"- Branch: `{branch}`"] if branch and branch != "HEAD" else []
if link:
    where.append(f"- Session: {link}")
note = f"**Needs you:** {reason}" + ("\n\n" + "\n".join(where) if where else "")

if number is None:
    made = api("POST", f"repos/{repo}/issues", {
        "title": ("Needs you: " + reason)[:120],
        "body": note + "\n\nOpened by the house board hook: a Claude session stopped "
                "to wait on you and had no card yet. Reply in that session and the "
                f"`{NEEDS}` label clears itself." + FOOTER,
        "labels": [NEEDS],
    })
    if not isinstance(made, dict) or not made.get("number"):
        sys.exit(0)
    number, is_pr, action = int(made["number"]), False, "opened"
else:
    if api("POST", f"repos/{repo}/issues/{number}/labels", {"labels": [NEEDS]}) is None:
        sys.exit(0)
    if not is_pr:
        api("DELETE", f"repos/{repo}/issues/{number}/labels/{DOING}")
    api("POST", f"repos/{repo}/issues/{number}/comments", {"body": note + FOOTER})
    action = "flagged"

save({"repo": repo, "number": number, "is_pr": is_pr, "flagged": True, "digest": digest})
print(json.dumps({"systemMessage": f"Board: {action} {repo}#{number} as {NEEDS}."}))
' "$mode" 2>/dev/null

exit 0
